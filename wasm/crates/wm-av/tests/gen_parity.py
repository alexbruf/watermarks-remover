def exc(e: Exception) -> dict:
    return {"error": {"type": type(e).__name__, "msg": str(e)}}


def inspect_dict(d: bytes) -> dict:
    r = av.inspect_av(Path("x.bin"), data=d).to_dict()
    del r["path"]
    return r


def clean(d: bytes, all_: bool) -> dict:
    with tempfile.TemporaryDirectory() as td:
        src, dst = Path(td) / "in.bin", Path(td) / "out.bin"
        src.write_bytes(d)
        try:
            r = av.clean_av(src, dst, strip_all_metadata=all_)
        except Exception as e:  # noqa: BLE001
            return exc(e)
        out = dst.read_bytes()
    for k in ("input", "output"):
        r.pop(k)
    r["sha"] = sha(out)
    return r


def call(fn, *a, **k):
    try:
        return fn(*a, **k)
    except Exception as e:  # noqa: BLE001
        return exc(e)


def ins(t):
    return {"c2pa": t[0], "ai": t[1], "findings": t[2]}


def strip_res(fn, d, all_, extra=False):
    try:
        r = fn(d, strip_all_metadata=all_)
    except Exception as e:  # noqa: BLE001
        return exc(e)
    o = {"sha": sha(r[0]), "len": len(r[0]), "actions": r[1]}
    if extra:
        o["incomplete"] = r[2]
    return o


def parse_res(d):
    try:
        p = av._parse_id3v2_frames(d)
    except Exception as e:  # noqa: BLE001
        return exc(e)
    if p is None:
        return None
    return {"total": p[0], "major": p[1], "frames": [[fid.hex(), sha(pl), len(pl)] for fid, pl in p[2]]}


def record(d: bytes, full: bool) -> dict:
    r = {
        "detect": av.detect_av_format(d),
        "inspect": call(inspect_dict, d),
        "clean_all": clean(d, True),
        "clean_keep": clean(d, False),
    }
    if full:
        r["direct"] = {
            "parse_id3": parse_res(d),
            "inspect_id3v2": call(lambda: ins(av._inspect_id3v2(d))),
            "inspect_mp4": call(lambda: ins(av._inspect_mp4(d))),
            "inspect_wav": call(lambda: ins(av._inspect_wav(d))),
            "inspect_flac": call(lambda: ins(av._inspect_flac(d))),
            "inspect_udta": call(lambda: ins(av._inspect_moov_udta(d))),
            "strip_id3v2": [strip_res(av._strip_id3v2, d, a) for a in (True, False)],
            "strip_mp4": [strip_res(av._strip_mp4, d, a, True) for a in (True, False)],
            "strip_wav": [strip_res(av._strip_wav, d, a) for a in (True, False)],
            "strip_flac": [strip_res(av._strip_flac, d, a) for a in (True, False)],
            "strip_udta": [strip_res(av._strip_moov_udta, d, a, True) for a in (True, False)],
        }
    return r


def main() -> None:
    if DATA.exists():
        shutil.rmtree(DATA)
    DATA.mkdir()
    rng = random.Random(20260604)
    cases = []
    for name, d in inputs.items():
        fn = name + ".bin"
        (DATA / fn).write_bytes(d)
        cases.append({"name": name, "file": fn, **record(d, True)})
        n = len(d)
        lens = sorted({k for k in (3, 8, 11, 12, 20, 36) if k < n})
        lens += sorted({rng.randrange(1, n) for _ in range(2)} - set(lens)) if n > 1 else []
        for k in lens:
            cases.append({"name": f"{name}@len{k}", "file": fn, "len": k, **record(d[:k], False)})
        for j in range(3):
            b = bytearray(d)
            edits = []
            for _ in range(rng.choice((1, 1, 2))):
                if not b:
                    break
                off = rng.randrange(min(len(b), 48)) if j % 2 == 0 else rng.randrange(len(b))
                val = rng.choice((0x00, 0xFF, 0x7F, 0x80, rng.randrange(256)))
                b[off] = val
                edits.append([off, val])
            if edits:
                cases.append({"name": f"{name}@mut{j}", "file": fn, "edits": edits, **record(bytes(b), False)})
    out = {"cases": cases}
    (DATA / "parity.json").write_text(json.dumps(out, separators=(",", ":")) + "\n")
    print(len(inputs), "inputs,", len(cases), "cases,", (DATA / "parity.json").stat().st_size, "bytes json")


if __name__ == "__main__":
    main()
