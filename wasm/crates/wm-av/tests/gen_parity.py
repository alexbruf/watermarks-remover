def id3_tag(major: int, body: bytes, flags: int = 0, footer: bool = False) -> bytes:
    f = b"3DI" + bytes([major, 0, flags]) + ssz(len(body)) if footer else b""
    return b"ID3" + bytes([major, 0, flags]) + ssz(len(body)) + body + f


def txxx(desc: bytes, val: bytes) -> bytes:
    return b"\x00" + desc + b"\x00" + val


def geob_enc(enc: int, mime: bytes, fn: bytes, desc: bytes, data: bytes) -> bytes:
    t = b"\x00" if enc in (0, 3) else b"\x00\x00"
    return bytes([enc]) + mime + b"\x00" + fn + t + desc + t + data


def flac_blocks(*blocks: tuple[int, bytes], last: int = 1) -> bytes:
    out = b"fLaC"
    for i, (t, p) in enumerate(blocks):
        h = t | (0x80 if i == len(blocks) - 1 and last else 0)
        out += bytes([h]) + len(p).to_bytes(3, "big") + p
    return out


def vorbis(*comments: bytes) -> bytes:
    v = b"ref libFLAC"
    o = struct.pack("<I", len(v)) + v + struct.pack("<I", len(comments))
    for c in comments:
        o += struct.pack("<I", len(c)) + c
    return o


