/// First index of `needle` in `hay` at or after `start`.
pub fn find_subslice_from(hay: &[u8], needle: &[u8], start: usize) -> Option<usize> {
    if start > hay.len() {
        return None;
    }
    if needle.is_empty() {
        return Some(start);
    }
    if needle.len() > hay.len() - start {
        return None;
    }
    let first = needle[0];
    let last_start = hay.len() - needle.len();
    let mut i = start;
    while i <= last_start {
        let p = hay[i..=last_start].iter().position(|&b| b == first)?;
        i += p;
        if &hay[i..i + needle.len()] == needle {
            return Some(i);
        }
        i += 1;
    }
    None
}

pub fn find_subslice(hay: &[u8], needle: &[u8]) -> Option<usize> {
    find_subslice_from(hay, needle, 0)
}

/// Python `needle in blob` for bytes.
pub fn contains_bytes(hay: &[u8], needle: &[u8]) -> bool {
    find_subslice(hay, needle).is_some()
}

/// Decode ASCII with `errors="replace"` (non-ASCII byte becomes U+FFFD).
pub fn ascii_replace(b: &[u8]) -> String {
    b.iter().map(|&c| if c < 0x80 { c as char } else { '\u{fffd}' }).collect()
}

/// Decode bytes as latin-1 (every byte maps to the same code point).
pub fn latin1(b: &[u8]) -> String {
    b.iter().map(|&c| c as char).collect()
}

/// Port of `_contains_any`: needle labels (in needle order) whose
/// ASCII-lowercased form occurs in the ASCII-lowercased blob.
pub fn contains_any(blob: &[u8], needles: &[&[u8]]) -> Vec<String> {
    contains_any_groups(blob, &[needles])
}

/// `_contains_any(blob, a + b + ...)` without building the concatenation.
pub fn contains_any_groups(blob: &[u8], groups: &[&[&[u8]]]) -> Vec<String> {
    let lower = blob.to_ascii_lowercase();
    let mut found = Vec::new();
    for group in groups {
        for n in group.iter() {
            let nl = n.to_ascii_lowercase();
            if !nl.is_empty() && find_subslice(&lower, &nl).is_some() {
                found.push(ascii_replace(n));
            }
        }
    }
    found
}

/// `_contains_any(blob, AI_META_HINTS + C2PA_MARKERS)`.
pub fn contains_ai_or_c2pa(blob: &[u8]) -> Vec<String> {
    contains_any_groups(blob, &[&AI_META_HINTS, &C2PA_MARKERS])
}

/// `bool(_contains_any(...))` shortcut for the combined table.
pub fn has_ai_or_c2pa(blob: &[u8]) -> bool {
    !contains_ai_or_c2pa(blob).is_empty()
}

/// `any(h.lower() in set for h in hits)`.
pub fn any_lower_in(hits: &[String], set: &[&str]) -> bool {
    hits.iter().any(|h| {
        let l = h.to_lowercase();
        set.iter().any(|s| *s == l)
    })
}

/// `", ".join(hits[:n])`.
pub fn join_first(hits: &[String], n: usize) -> String {
    hits.iter().take(n).cloned().collect::<Vec<_>>().join(", ")
}

/// Python `repr()` of a bytes object (used in the "truncated chunk b'IDAT'"
/// finding).
pub fn py_bytes_repr(b: &[u8]) -> String {
    let has_sq = b.contains(&b'\'');
    let has_dq = b.contains(&b'"');
    let quote = if has_sq && !has_dq { b'"' } else { b'\'' };
    let mut s = String::with_capacity(b.len() + 3);
    s.push('b');
    s.push(quote as char);
    for &c in b {
        match c {
            b'\\' => s.push_str("\\\\"),
            b'\t' => s.push_str("\\t"),
            b'\n' => s.push_str("\\n"),
            b'\r' => s.push_str("\\r"),
            c if c == quote => {
                s.push('\\');
                s.push(c as char);
            }
            0x20..=0x7e => s.push(c as char),
            _ => s.push_str(&format!("\\x{c:02x}")),
        }
    }
    s.push(quote as char);
    s
}

/// Bounds-checked big/little-endian readers (never panic).
pub fn rd_u16(data: &[u8], at: usize, little: bool) -> Option<u16> {
    let b: [u8; 2] = data.get(at..at.checked_add(2)?)?.try_into().ok()?;
    Some(if little { u16::from_le_bytes(b) } else { u16::from_be_bytes(b) })
}

pub fn rd_u32(data: &[u8], at: usize, little: bool) -> Option<u32> {
    let b: [u8; 4] = data.get(at..at.checked_add(4)?)?.try_into().ok()?;
    Some(if little { u32::from_le_bytes(b) } else { u32::from_be_bytes(b) })
}

pub fn rd_u64(data: &[u8], at: usize, little: bool) -> Option<u64> {
    let b: [u8; 8] = data.get(at..at.checked_add(8)?)?.try_into().ok()?;
    Some(if little { u64::from_le_bytes(b) } else { u64::from_be_bytes(b) })
}

/// Python `data[a:b]` (clamped, never panics; empty when `a >= b`).
pub fn slice_clamped(data: &[u8], a: usize, b: usize) -> &[u8] {
    let b = b.min(data.len());
    if a >= b {
        &[]
    } else {
        &data[a..b]
    }
}

