/// Port of `common.classify_finding_confidence`.
pub fn classify_finding_confidence(finding: &str) -> &'static str {
    let t = finding.to_lowercase();

    if t.starts_with("layer-a") && t.ends_with("(space)") {
        return "informational";
    }

    const CONFIRMED: [&str; 12] = [
        "c2patool reports",
        "c2pa-related manifest",
        "png chunk c2",
        "png chunk cabx",
        "png chunk jumb",
        "png chunk jumd",
        "jpeg app11 segment",
        "digital_source_type",
        "digitalsourcetype",
        "trainedalgorithmicmedia",
        "compositewithtrainedalgorithmicmedia",
        "softwareagent",
    ];
    if CONFIRMED.iter().any(|s| t.contains(s)) {
        return "confirmed";
    }

    const INFORMATIONAL: [&str; 11] = [
        "cms generator",
        "customxml parts",
        "xmp packet present",
        "unsupported",
        "not fully inspected",
        "format not",
        "svg <metadata> present",
        "not a valid",
        "truncated chunk",
        "bad segment length",
        "svg decode note",
    ];
    if t.starts_with("info:") || INFORMATIONAL.iter().any(|s| t.contains(s)) {
        return "informational";
    }

    if t.contains("byte-scan") {
        return "likely_false_positive";
    }

    const PROBABLE: [&str; 13] = [
        "ai:",
        "marker:",
        "meta:",
        "frontmatter",
        "json-ld",
        "attr:",
        "png ",
        "jpeg app",
        "exif",
        "xmp",
        "interesting",
        "pdf-structured",
        "layer-a",
    ];
    if PROBABLE.iter().any(|s| t.contains(s)) {
        return "probable";
    }

    "informational"
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_match_python_lengths() {
        assert_eq!(AI_META_HINTS.len(), 17);
        assert_eq!(JPEG_COM_AI_HINTS.len(), 14);
        assert_eq!(ai_and_c2pa_needles().len(), 26);
        assert_eq!(AI_GENERATOR_PRODUCTS.len(), 31);
    }

    #[test]
    fn repr_matches_python() {
        assert_eq!(py_bytes_repr(b"IDAT"), "b'IDAT'");
        assert_eq!(py_bytes_repr(b"a'b"), "b\"a'b\"");
        assert_eq!(py_bytes_repr(b"a'b\"c"), "b'a\\'b\"c'");
        assert_eq!(py_bytes_repr(&[0, 0xff, b'\\', b'\n']), "b'\\x00\\xff\\\\\\n'");
    }

    #[test]
    fn contains_any_is_case_insensitive_and_ordered() {
        let hits = contains_any(b"xx CONTENTCREDENTIALS c2pa", &[b"c2pa", b"C2PA", b"nope"]);
        assert_eq!(hits, vec!["c2pa", "C2PA"]);
    }
}
