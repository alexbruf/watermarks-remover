def webp_chunk(fourcc: bytes, payload: bytes, pad: bytes | None = None) -> bytes:
    padding = (pad if pad is not None else b"\x00") if len(payload) & 1 else b""
    return fourcc + struct.pack("<I", len(payload)) + payload + padding


def webp(*chunks: tuple, riff_delta: int = 0, tail: bytes = b"") -> bytes:
    body = b"WEBP" + b"".join(webp_chunk(*c) for c in chunks) + tail
    return b"RIFF" + struct.pack("<I", len(body) + riff_delta) + body


