def main() -> None:
    DATA.mkdir(parents=True, exist_ok=True)
    for old in DATA.iterdir():
        if old.is_file():
            old.unlink()

    bases: dict[str, bytes] = {}
    for fn in (make_png_cases, make_jpeg_cases, make_webp_cases, make_isobmff_cases, make_gif_cases, make_bmp_cases, make_tiff_cases, make_misc_cases):
        bases.update(fn())

    # All inputs are stored as files in tests/data; keep them small.
    LARGE = {n for n, b in bases.items() if len(b) > 20000}
    assert not LARGE, f"inputs too large to store: {sorted(LARGE)}"
    for name, data in bases.items():
        (DATA / name).write_bytes(data)

    cases = []
    for name, data in bases.items():
        cases.append({"id": name, "input": {"file": name}, "result": run_case(data, True)})

    # truncated prefixes + byte mutations derived from each base input
    fuzz = []
    for name, data in bases.items():
        rng = random.Random(zlib.crc32(name.encode()))
        n = len(data)
        cuts = {0, 3, 9, 17, n // 3, (2 * n) // 3, n - 1}
        cuts = sorted(c for c in cuts if 0 <= c < n)
        specs = [{"file": name, "len": c} for c in cuts]
        if n:
            for _ in range(2):
                edits = []
                for _ in range(rng.choice([1, 2, 3])):
                    edits.append([rng.randrange(n), rng.choice([0x00, 0xFF, 0x7F, 0x80, 0x01, rng.randrange(256)])])
                specs.append({"file": name, "edits": edits})
        for i, spec in enumerate(specs):
            mutated = apply_spec(data, spec)
            fuzz.append({"id": f"{name}#{i}", "input": spec, "result": run_case(mutated, False)})

    out = {
        "generator": "tests/gen_parity.py",
        "cases": cases,
        "fuzz": fuzz,
        "zlib": make_zlib_cases(),
    }
    (DATA / "parity.json").write_text(json.dumps(out, separators=(",", ":")) + "\n")

    nonvalue = {}
    for case in cases + fuzz:
        def walk(o):
            if isinstance(o, dict):
                if "error" in o and isinstance(o["error"], dict) and "type" in o["error"]:
                    t = o["error"]["type"]
                    if t != "ValueError":
                        nonvalue[t] = nonvalue.get(t, 0) + 1
                else:
                    for v in o.values():
                        walk(v)
        walk(case["result"])
    print(f"base cases: {len(cases)}  fuzz cases: {len(fuzz)}  zlib cases: {len(out['zlib'])}")
    print(f"non-ValueError python exceptions recorded: {nonvalue}")
    shutil.rmtree(TMP, ignore_errors=True)


if __name__ == "__main__":
    main()
