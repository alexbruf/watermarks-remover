def zlib_outcome(data: bytes) -> dict:
    try:
        out = im._zlib_decompress_bounded(data)
        return {"ok": {"n": len(out), "sha256": sha(out)}}
    except im.PngTextBudgetExceeded:
        return {"budget": True}
    except zlib.error:
        return {"corrupt": True}


def make_zlib_cases() -> list[dict]:
    rng = random.Random(99)
    payloads = [
        b"",
        b"a",
        b"ChatGPT",
        b"Generated by AI " * 30,
        bytes(range(256)) * 3,
        b"abcabcabcabcabcabc" * 50 + b"tail",
        bytes(rng.randrange(256) for _ in range(300)),
        (b"The quick brown fox jumps over the lazy dog. " * 40),
    ]
    streams: list[tuple[str, bytes]] = []
    for pi, p in enumerate(payloads):
        for lvl in (0, 1, 6, 9):
            streams.append((f"p{pi}_l{lvl}", zlib.compress(p, lvl)))
        for strat_name, strat in (("fixed", zlib.Z_FIXED), ("huff", zlib.Z_HUFFMAN_ONLY), ("rle", zlib.Z_RLE)):
            co = zlib.compressobj(6, zlib.DEFLATED, 15, 8, strat)
            streams.append((f"p{pi}_{strat_name}", co.compress(p) + co.flush()))
        co = zlib.compressobj(6, zlib.DEFLATED, 15)
        parts = co.compress(p[: len(p) // 2]) + co.flush(zlib.Z_FULL_FLUSH) + co.compress(p[len(p) // 2 :]) + co.flush()
        streams.append((f"p{pi}_multi", parts))
    cases = []
    for name, s in streams:
        cases.append({"id": name, "hex": s.hex(), "expect": zlib_outcome(s)})
        # every prefix for short streams, a sample for long ones
        lens = range(len(s)) if len(s) <= 40 else sorted(set(rng.randrange(len(s)) for _ in range(10)))
        for k in lens:
            cases.append({"id": f"{name}_cut{k}", "hex": s[:k].hex(), "expect": zlib_outcome(s[:k])})
        for j in range(5):
            b = bytearray(s)
            for _ in range(rng.choice([1, 1, 2, 3])):
                if b:
                    b[rng.randrange(len(b))] = rng.choice([0, 0xFF, rng.randrange(256)])
            cases.append({"id": f"{name}_mut{j}", "hex": bytes(b).hex(), "expect": zlib_outcome(bytes(b))})
        extra = s + b"trailing garbage"
        cases.append({"id": f"{name}_trail", "hex": extra.hex(), "expect": zlib_outcome(extra)})
    # headers
    for hdr in (b"", b"\x78", b"\x78\x9c", b"\x78\x01", b"\x78\xda", b"\x08\x1d", b"\x78\xbb\x00\x00\x00\x00", b"\x78\xbb\x00\x00", b"\x78\xbb", b"\x79\x9c", b"\x68\x81", b"\x88\x1d", b"\x00\x00", b"\xff\xff"):
        cases.append({"id": f"hdr_{hdr.hex()}", "hex": hdr.hex(), "expect": zlib_outcome(hdr)})
    # random garbage behind a valid header
    for j in range(100):
        n = rng.randrange(1, 60)
        s = b"\x78\x9c" + bytes(rng.randrange(256) for _ in range(n))
        cases.append({"id": f"garbage{j}", "hex": s.hex(), "expect": zlib_outcome(s)})
    # budget boundaries
    for n in (1 << 20, (1 << 20) - 1, (1 << 20) + 1, 3 << 20):
        s = zlib.compress(b"\x00" * n, 9)
        cases.append({"id": f"zeros_{n}", "hex": s.hex(), "expect": zlib_outcome(s)})
        s2 = zlib.compress(bytes((i * 7) & 0xFF for i in range(n)), 1)
        cases.append({"id": f"pattern_{n}", "hex": s2.hex(), "expect": zlib_outcome(s2)})
        cases.append({"id": f"zeros_{n}_cut", "hex": s[:-6].hex(), "expect": zlib_outcome(s[:-6])})
    co = zlib.compressobj(0)
    stored = co.compress(b"\x01" * 70000) + co.flush()
    cases.append({"id": "stored_70000", "hex": stored.hex(), "expect": zlib_outcome(stored)})
    return cases


