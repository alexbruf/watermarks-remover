def mk_tiff(ifds, little=True, big=False, extra_tail=b""):
    """Tiny TIFF builder. ifds: list of list of (tag, type, count, payload|int-offset-marker)."""
    bo = "<" if little else ">"
    off_len = 8 if big else 4
    count_len = 8 if big else 2
    entry_size = 20 if big else 12
    header_size = 16 if big else 8
    off_fmt = bo + ("Q" if big else "I")
    count_fmt = bo + ("Q" if big else "H")
    layout = []
    cursor = header_size
    ifd_offs = []
    for ents in ifds:
        ifd_offs.append(cursor)
        cursor += count_len + len(ents) * entry_size + off_len
    data_area = bytearray()
    base = cursor
    blocks = []
    for i, ents in enumerate(ifds):
        blk = bytearray(struct.pack(count_fmt, len(ents)))
        for tag, typ, count, payload in ents:
            if isinstance(payload, tuple):  # ("ptr", ifd_index)
                val = struct.pack(off_fmt, ifd_offs[payload[1]])
            elif len(payload) <= off_len:
                val = payload + b"\x00" * (off_len - len(payload))
            else:
                if len(data_area) & 1:
                    data_area.append(0)
                val = struct.pack(off_fmt, base + len(data_area))
                data_area.extend(payload)
            blk += struct.pack(bo + "HH", tag, typ) + struct.pack(off_fmt, count) + val
        nxt = ifd_offs[i + 1] if i + 1 < len(ifds) else 0
        blk += struct.pack(off_fmt, nxt)
        blocks.append(bytes(blk))
    magic = b"II" if little else b"MM"
    if big:
        hdr = magic + struct.pack(bo + "HHHQ", 43, 8, 0, ifd_offs[0])
    else:
        hdr = magic + struct.pack(bo + "HI", 42, ifd_offs[0])
    return hdr + b"".join(blocks) + bytes(data_area) + extra_tail


