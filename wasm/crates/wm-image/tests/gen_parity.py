def run_inspector(name, data):
    def go():
        c2pa, ai, findings = INSPECTORS[name](data)
        return {"has_c2pa": c2pa, "has_ai": ai, "findings": findings}

    return attempt(go)


def run_strip(name, data, strip_all):
    def go():
        out, actions = STRIPPERS[name](data, strip_all)
        return {"sha256": sha(out), "n": len(out), "actions": actions}

    return attempt(go)


def run_inspect_image(data):
    def go():
        src = TMP / "in.bin"
        src.write_bytes(data)
        r = im.inspect_image(src, data=data, run_synthid=False, include_exiftool=False).to_dict()
        return {
            "format": r["format"],
            "has_c2pa": r["has_c2pa"],
            "has_ai_metadata": r["has_ai_metadata"],
            "findings": r["findings"],
            "findings_confidence": r["findings_confidence"],
            "notes": r["notes"],
        }

    return attempt(go)


def run_clean(data, strip_all):
    def go():
        src = TMP / "c_in.bin"
        dest = TMP / "c_out.bin"
        if dest.exists():
            dest.unlink()
        src.write_bytes(data)
        r = im.clean_image(src, dest, strip_all_metadata=strip_all)
        out = dest.read_bytes()
        return {
            "format": r["format"],
            "actions": r["actions"],
            "bytes_in": r["bytes_in"],
            "bytes_out": r["bytes_out"],
            "changed": r["changed"],
            "still_has_c2pa": r["still_has_c2pa"],
            "still_has_ai_metadata": r["still_has_ai_metadata"],
            "post_findings": r["post_findings"],
            "sha256": sha(out),
        }

    return attempt(go)


def compact(r: dict) -> dict:
    """Fuzz cases omit fields that are pure functions of other recorded ones."""
    if "error" in r:
        return r
    return {k: v for k, v in r.items() if k not in ("actions", "findings_confidence", "format", "bytes_in")}


def run_case(data: bytes, full: bool) -> dict:
    res: dict = {"detect": im.detect_format(data), "inspect_image": run_inspect_image(data)}
    res["clean"] = {"all": run_clean(data, True), "keep": run_clean(data, False)}
    if not full:
        res["inspect_image"] = compact(res["inspect_image"])
        res["clean"] = {k: compact(v) for k, v in res["clean"].items()}
    if full:
        res["inspectors"] = {n: run_inspector(n, data) for n in INSPECTORS}
        res["strip"] = {
            f"{n}_{mode}": run_strip(n, data, mode == "all")
            for n in STRIPPERS
            for mode in ("all", "keep")
        }
    else:
        fmt = res["detect"]
        if fmt in INSPECTORS:
            res["inspectors"] = {fmt: run_inspector(fmt, data)}
            res["strip"] = {f"{fmt}_{m}": run_strip(fmt, data, m == "all") for m in ("all", "keep")}
        else:
            res["inspectors"] = {}
            res["strip"] = {}
    return res


def apply_spec(base: bytes, spec: dict) -> bytes:
    b = bytearray(base)
    for off, val in spec.get("edits", []):
        b[off] = val
    n = spec.get("len")
    return bytes(b[:n]) if n is not None else bytes(b)


