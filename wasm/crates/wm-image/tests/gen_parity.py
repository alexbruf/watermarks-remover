def png_chunk(ctype: bytes, payload: bytes) -> bytes:
    crc = zlib.crc32(ctype)
    crc = zlib.crc32(payload, crc) & 0xFFFFFFFF
    return struct.pack(">I", len(payload)) + ctype + payload + struct.pack(">I", crc)


PNG_SIG = b"\x89PNG\r\n\x1a\n"
IHDR = png_chunk(b"IHDR", struct.pack(">IIBBBBB", 1, 1, 8, 2, 0, 0, 0))
IDAT = png_chunk(b"IDAT", zlib.compress(b"\x00\x00\x00"))
IEND = png_chunk(b"IEND", b"")


def png_with(*chunks: bytes, end: bool = True, idat: bytes = IDAT) -> bytes:
    return PNG_SIG + IHDR + b"".join(chunks) + idat + (IEND if end else b"")


def text(key: str, value: str) -> bytes:
    return key.encode("latin-1") + b"\x00" + value.encode("latin-1")


def itxt(key: bytes, comp: int, lang: bytes, tkey: bytes, value: bytes) -> bytes:
    return key + b"\x00" + bytes([comp, 0]) + lang + b"\x00" + tkey + b"\x00" + value


