def box(fourcc: bytes, payload: bytes) -> bytes:
    return struct.pack(">I", len(payload) + 8) + fourcc + payload


def box64(fourcc: bytes, payload: bytes) -> bytes:
    return struct.pack(">I4sQ", 1, fourcc, len(payload) + 16) + payload


def fullbox(fourcc: bytes, payload: bytes, version: int = 0, flags: int = 0) -> bytes:
    return box(fourcc, struct.pack(">I", (version << 24) | flags) + payload)


