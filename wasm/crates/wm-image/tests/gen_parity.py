def err(e: BaseException) -> dict:
    return {"error": {"type": type(e).__name__, "msg": str(e)}}


def attempt(fn):
    try:
        return fn()
    except Exception as e:  # noqa: BLE001 -- recording Python behaviour
        return err(e)


